import { useEffect, useRef, useState } from "react";
import { api } from "./api";
import ConditionStep from "./components/ConditionStep";
import DepartmentStep from "./components/DepartmentStep";
import ResultsView from "./components/ResultsView";
import type { GenerateRequest, JobEvent, JobStatus, Sample } from "./types";

interface ConditionList {
  department: string;
  conditions: string[];
  source: "seed" | "llm";
}

export default function App() {
  const [health, setHealth] = useState<{ mode: string; model: string; max_samples_per_job: number } | null>(null);
  const [conditionList, setConditionList] = useState<ConditionList | null>(null);
  const [job, setJob] = useState<JobStatus | null>(null);
  const [samples, setSamples] = useState<Map<number, Sample>>(new Map());
  const [errors, setErrors] = useState<Map<number, string>>(new Map());
  const [submitError, setSubmitError] = useState<string | null>(null);
  const unsubscribe = useRef<(() => void) | null>(null);

  useEffect(() => {
    api.health().then(setHealth).catch(() => setHealth(null));
    return () => unsubscribe.current?.();
  }, []);

  const running = job?.status === "planning" || job?.status === "running";

  function onEvent(event: JobEvent) {
    switch (event.type) {
      case "status": {
        const { type: _, ...status } = event;
        setJob(status);
        break;
      }
      case "sample":
        setSamples((m) => new Map(m).set(event.index, event.sample));
        break;
      case "sample_error":
        setErrors((m) => new Map(m).set(event.index, event.error));
        break;
      case "done":
        setJob((j) => (j ? { ...j, status: event.status, error: event.error } : j));
        break;
    }
  }

  async function generate(req: GenerateRequest) {
    setSubmitError(null);
    try {
      const status = await api.generate(req);
      setSamples(new Map());
      setErrors(new Map());
      setJob(status);
      unsubscribe.current?.();
      unsubscribe.current = api.stream(status.job_id, onEvent);
    } catch (e) {
      setSubmitError((e as Error).message);
    }
  }

  function reset() {
    unsubscribe.current?.();
    setJob(null);
    setSamples(new Map());
    setErrors(new Map());
  }

  const orderedSamples = [...samples.entries()].sort(([a], [b]) => a - b).map(([, s]) => s);
  const orderedErrors = [...errors.entries()].sort(([a], [b]) => a - b).map(([index, error]) => ({ index, error }));

  return (
    <div className="page">
      <header className="page-header">
        <h1>Synthetic Patient Data Generator</h1>
        <p className="muted">
          Build labeled, fully synthetic patient records for evaluating LLMs.
          {health && (
            <>
              {" "}
              Model: <code>{health.mode === "mock" ? "mock (no API calls)" : health.model}</code>
            </>
          )}
        </p>
      </header>

      <DepartmentStep
        disabled={running}
        onLoaded={(department, conditions, source) => setConditionList({ department, conditions, source })}
      />

      {conditionList && (
        <ConditionStep
          key={`${conditionList.department}|${conditionList.conditions.join("|")}`}
          {...conditionList}
          disabled={running}
          maxSamples={health?.max_samples_per_job ?? 500}
          onGenerate={generate}
        />
      )}
      {submitError && <p className="error">{submitError}</p>}

      {job && (
        <ResultsView
          status={job}
          samples={orderedSamples}
          errors={orderedErrors}
          onCancel={() => api.cancel(job.job_id).catch(() => undefined)}
          onReset={reset}
        />
      )}

      <footer className="muted small">
        All records are synthetic and generated by an LLM. They may contain clinical errors and must not be used
        for patient care.
      </footer>
    </div>
  );
}
